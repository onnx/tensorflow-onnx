"""Tests for the dependency-free support-status generator."""

import tempfile
import textwrap
import unittest
from pathlib import Path

from tools.gen_doc import collect_handler_versions, render_support_status


class GenDocTest(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.repo_root = Path(self.temp_dir.name)
        for relative in (
            "tf2onnx/custom_opsets",
            "tf2onnx/onnx_opset",
            "tf2onnx/tflite_handlers",
        ):
            (self.repo_root / relative).mkdir(parents=True)

    def tearDown(self):
        self.temp_dir.cleanup()

    def write_source(self, relative, source):
        path = self.repo_root / relative
        path.write_text(textwrap.dedent(source), encoding="utf-8")

    def test_collects_literal_names_domains_inheritance_and_unsupported_versions(self):
        self.write_source(
            "tf2onnx/onnx_opset/common.py",
            """
            class BroadcastOp:
                @classmethod
                def version_1(cls, ctx, node, **kwargs):
                    pass

                @classmethod
                def version_6(cls, ctx, node, **kwargs):
                    pass
            """,
        )
        self.write_source(
            "tf2onnx/onnx_opset/operators.py",
            """
            from tf2onnx.onnx_opset import common

            @tf_op(["Add", "Sub"])
            class Broadcast(common.BroadcastOp):
                pass

            @tf_op("ReverseSequence")
            class ReverseSequence:
                @classmethod
                def version_8(cls, ctx, node, **kwargs):
                    pass

                @classmethod
                def version_9(cls, ctx, node, **kwargs):
                    raise NotImplementedError()

                @classmethod
                def version_10(cls, ctx, node, **kwargs):
                    pass
            """,
        )
        self.write_source(
            "tf2onnx/custom_opsets/ms.py",
            """
            @tf_op("Range", domain=constants.MICROSOFT_DOMAIN)
            class Range:
                @classmethod
                def version_1(cls, ctx, node, **kwargs):
                    pass
            """,
        )
        self.write_source(
            "tf2onnx/tflite_handlers/rewrite.py",
            """
            @tfl_op("TFL_REWRITE_ONLY")
            class RewriteOnly:
                @classmethod
                def to_tf(cls, ctx, node, **kwargs):
                    pass
            """,
        )

        handlers = collect_handler_versions(self.repo_root)

        self.assertEqual(handlers[""]["Add"], {1: False, 6: False})
        self.assertEqual(handlers[""]["Sub"], {1: False, 6: False})
        self.assertEqual(handlers[""]["ReverseSequence"], {8: False, 9: True, 10: False})
        self.assertEqual(handlers["com.microsoft"]["Range"], {1: False})
        self.assertNotIn("TFL_REWRITE_ONLY", handlers[""])

    def test_renders_generated_warning_disclaimer_and_ranges(self):
        handlers = {
            "": {
                "Add": {1: False, 6: False},
                "ReverseSequence": {8: False, 9: True, 10: False},
            },
            "com.microsoft": {"Range": {1: False}},
        }

        markdown = render_support_status(handlers)

        self.assertIn("Generated by tools/gen_doc.py", markdown)
        self.assertIn("does not guarantee", markdown)
        self.assertIn("| Add | 1–21 |", markdown)
        self.assertIn("| ReverseSequence | 8–21 (except 9) |", markdown)
        self.assertIn("| Range | 1 |", markdown)


class RepositoryInventoryTest(unittest.TestCase):
    def test_repository_inventory_has_expected_domains_and_representative_handlers(self):
        repo_root = Path(__file__).resolve().parents[1]
        handlers = collect_handler_versions(repo_root)

        self.assertGreater(len(handlers[""]), 250)
        self.assertIn("Conv2D", handlers[""])
        self.assertIn("TFL_QUANTIZE", handlers[""])
        self.assertIn("Range", handlers["com.microsoft"])
        self.assertIn("StringSplit", handlers["ai.onnx.contrib"])


if __name__ == "__main__":
    unittest.main()
